/** Потолок персональной скидки ученика. Бизнес-правило, а не структурное ограничение БД. */
export const MAX_STUDENT_DISCOUNT_PERCENT = 10;

/**
 * Цена занятия для ученика со скидкой.
 *
 * Округление делается на каждом занятии, а не на итоге счёта: баланс хранится в целых
 * единицах валюты, и округлённый итог разошёлся бы с суммой поштучных списаний —
 * на последнее занятие не хватило бы денег.
 *
 * При нулевой скидке возвращается исходная цена без арифметики: у подавляющего большинства
 * учеников скидки нет, и их расчёты должны остаться побайтово прежними.
 */
export const applyDiscount = (priceMajor: number, discountPercent: number): number => {
	if (!discountPercent) {
		return priceMajor;
	}
	return Math.round((priceMajor * (100 - discountPercent)) / 100);
};
