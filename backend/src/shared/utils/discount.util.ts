/** Потолок персональной скидки ученика. Бизнес-правило, а не структурное ограничение БД. */
export const MAX_STUDENT_DISCOUNT_PERCENT = 10;

/**
 * Цена занятия для ученика со скидкой, в минорных единицах валюты.
 *
 * Округление до копейки: 3400 (34,00) со скидкой 10% → 3060 (30,60). Делается на каждом
 * занятии, а не на итоге счёта: баланс списывается поштучно, и округлённый итог разошёлся бы
 * с суммой поштучных списаний — на последнее занятие не хватило бы денег.
 *
 * При нулевой скидке возвращается исходная цена без арифметики: у подавляющего большинства
 * учеников скидки нет, и их расчёты должны остаться побайтово прежними.
 */
export const applyDiscount = (priceMinor: number, discountPercent: number): number => {
	if (!discountPercent) {
		return priceMinor;
	}
	return Math.round((priceMinor * (100 - discountPercent)) / 100);
};
