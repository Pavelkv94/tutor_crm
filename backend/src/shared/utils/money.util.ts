/**
 * Все денежные величины проекта хранятся и передаются в минорных единицах валюты:
 * 3060 — это 30,60. Целое, а не дробное: скидка и конверсия дают копейки, а плавающая
 * точка в денежных расчётах не используется нигде.
 */

/** Минорных единиц в одной единице валюты. */
export const MONEY_MINOR_UNITS = 100;

/**
 * «30,60» из 3060 — для текстов счетов и уведомлений. Копейки печатаются всегда, даже
 * нулевые: администратор читает суммы столбиком, и плавающее число знаков сбивает.
 * Разделитель — запятая: все тексты русские.
 */
export const formatMoneyMinor = (amountMinor: number): string => (amountMinor / MONEY_MINOR_UNITS).toFixed(2).replace(".", ",");
