-- Перевод всех денежных величин из целых единиц валюты в минорные: 34 → 3400.
--
-- Причина — скидка ученика. Она применяется к цене каждого занятия, а не к итогу счёта
-- (баланс закрывает занятия поштучно), и в целых единицах 10% от 34 округлялись до 31,
-- то есть фактическая скидка оказывалась 8.8%, а не 10%. В минорных единицах то же
-- округление даёт ровно 30,60.
--
-- Тип колонок не меняется — меняется цена деления. Пересчитать нужно все денежные
-- колонки разом: инвариант BalanceService (balance = Σ приходов − Σ списаний) должен
-- сойтись и после миграции, а масштабирование обеих частей равенства его сохраняет.
--
-- Не трогаем: school_settings.eur_rate, payment.charge_rate (сотые доли курса),
-- payment.charge_amount_minor (уже минорные единицы), student.discount (проценты).

UPDATE "student" SET "balance" = "balance" * 100 WHERE "balance" <> 0;
UPDATE "plan" SET "plan_price" = "plan_price" * 100 WHERE "plan_price" <> 0;
UPDATE "payment" SET "amount" = "amount" * 100 WHERE "amount" <> 0;
UPDATE "lesson_payment" SET "amount" = "amount" * 100 WHERE "amount" <> 0;
