-- Персональная скидка ученика.
--
-- Скидка применяется к цене каждого занятия, а не к итогу счёта. Иначе не сходится
-- арифметика аллокации: BalanceService закрывает занятия поштучно, списывая с баланса
-- цену занятия, и уменьшенного на скидку платежа не хватило бы на последнее занятие —
-- оно осталось бы неоплаченным, а остаток повис бы на балансе.
--
-- Бэкфилл не нужен: у всех существующих учеников скидки нет, дефолт 0 даёт ровно
-- прежнее поведение.

-- AlterTable
ALTER TABLE "student" ADD COLUMN "discount" INTEGER NOT NULL DEFAULT 0;

-- Структурная защита арифметики. Потолок в 10% — бизнес-политика, она живёт в валидации
-- DTO (MAX_STUDENT_DISCOUNT_PERCENT) и не должна требовать миграции при изменении.
-- Prisma CHECK в схеме выразить не умеет, поэтому констрейнт дописан руками.
ALTER TABLE "student" ADD CONSTRAINT "student_discount_check"
  CHECK ("discount" >= 0 AND "discount" <= 100);

-- Скидка, по которой был посчитан счёт. Оплата раскладывается по этому снимку, а не по
-- текущей скидке ученика: иначе правка скидки между выставлением и оплатой снова оставила бы
-- занятие незакрытым.
ALTER TABLE "payment" ADD COLUMN "discount_percent" INTEGER NOT NULL DEFAULT 0;
