-- Способ оплаты ученика.
--
-- До сих пор решение «выставлять ссылку Stripe или просить чек» принималось по валюте
-- занятий: BYN — чек, EUR/PLN — ссылка. Это неверно по существу — школа принимает
-- белорусские платежи и картой тоже, — и не даёт админу никакого управления. Теперь
-- решает персональное поле ученика, а валюта отвечает только за то, в чём считается счёт.
--
-- ВНИМАНИЕ: бэкфилла нет намеренно. У всех существующих учеников поле остаётся NULL,
-- то есть до ручной простановки способа ссылки перестают выставляться и всем уходит
-- текст с просьбой прислать чек. Проставить способ нужно до 1-го числа, когда отработает
-- крон ежемесячного выставления счетов.

-- CreateEnum
CREATE TYPE "PaymentMethod" AS ENUM ('STRIPE', 'BYN_ACCOUNT');

-- AlterTable
ALTER TABLE "student" ADD COLUMN "payment_method" "PaymentMethod";
